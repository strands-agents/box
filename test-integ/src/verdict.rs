    //! Fault injection for the reducer: every way a partial or broken run could
    //! read as GREEN must come out RED with a named problem.
    use super::*;

    const SUITE: &[CaseSpec] = &[
        CaseSpec {
            id: "PO-1",
            category: "policy",
            platforms: &[],
        },
        CaseSpec {
            id: "CN-1",
            category: "containment",
            platforms: &[],
        },
        CaseSpec {
            id: "CN-MAC",
            category: "containment",
            platforms: &["macos"],
        },
    ];

    fn row(id: &str, category: &str, result: &str, note: &str) -> Row {
        Row {
            id: id.into(),
            category: category.into(),
            description: "d".into(),
            result: result.into(),
            note: note.into(),
        }
    }

    fn complete_linux() -> Vec<Row> {
        vec![
            row("PO-1", "policy", "PASS", ""),
            row("CN-1", "containment", "PASS", ""),
            row(
                "CN-MAC",
                "containment",
                "SKIP",
                &format!("{SKIP_NOTE_PREFIX}linux: declared for [macos]"),
            ),
        ]
    }

    fn build(rows: Vec<Row>, malformed: Vec<String>, status: Option<i32>) -> Summary {
        Summary::build("linux", "abc", Rows { rows, malformed }, SUITE, status)
    }

    #[test]
    fn complete_run_with_declared_skip_is_green() {
        let s = build(complete_linux(), vec![], Some(0));
        assert_eq!(s.verdict, "GREEN", "{:?}", s.integrity.problems);
        assert_eq!(
            s.counts,
            Counts {
                total: 3,
                pass: 2,
                fail: 0,
                error: 0,
                skip: 1
            }
        );
        assert_eq!(s.integrity.expected, 3);
        assert_eq!(s.integrity.recorded, 3);
    }

