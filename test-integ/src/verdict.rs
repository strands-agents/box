    #[test]
    fn the_old_integrity_faults_still_defeat_a_quarantined_green() {
        // Missing row.
        let rows: Vec<Row> = complete_linux_quarantined()
            .into_iter()
            .filter(|r| r.id != "CN-E-01")
            .collect();
        let s = build_on("linux", rows, Some(0));
        assert_eq!(s.verdict, "RED");
        assert!(
            s.integrity
                .problems
                .iter()
                .any(|p| p.starts_with("CN-E-01: no row recorded"))
        );
        // Duplicate quarantined row.
        let mut rows = complete_linux_quarantined();
        rows.push(row("CN-W-05", "containment", "SKIP", &qnote("CN-W-05")));
        let s = build_on("linux", rows, Some(0));
        assert_eq!(s.verdict, "RED");
        assert!(
            s.integrity
                .problems
                .iter()
                .any(|p| p.contains("CN-W-05: 2 rows recorded (duplicate id)"))
        );
        // Cargo failure and unreported cargo status.
        assert_eq!(
            build_on("linux", complete_linux_quarantined(), Some(101)).verdict,
            "RED"
        );
        assert_eq!(
            build_on("linux", complete_linux_quarantined(), None).verdict,
            "RED"
        );
        // Another case failing stays RED.
        let mut rows = complete_linux_quarantined();
        rows[1] = row(
            "CN-E-01",
            "containment",
            "ERROR",
            "no shell:exec decision was journaled … 2411 Killed: 9 zsh",
        );
        let s = build_on("linux", rows, Some(101));
        assert_eq!(s.verdict, "RED");
        assert_eq!(s.counts.error, 1);
        // Malformed row alongside the quarantine.
        let s = Summary::build(
            "linux",
            "abc",
            Rows {
                rows: complete_linux_quarantined(),
                malformed: vec!["x.jsonl: not json".into()],
            },
            QUARANTINE_SUITE,
            Some(0),
        );
        assert_eq!(s.verdict, "RED");
        // Wrong platform/commit are the collector's checks and unchanged; the document still names them.
        assert_eq!(s.platform, "linux");
        assert_eq!(s.box_commit, "abc");
    }

