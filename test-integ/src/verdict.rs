//! verdict.rs — per-test rows and the reducer into the pipeline contract.
//!
//! Each `#[test]` writes its own `<id>.jsonl` row (like the bash harness appended
//! a JSONL row per assertion). `emit-verdict` then reduces every row into the
//! `verdict.json` the pipeline already consumes:
//!
//! ```json
//! {
//!   "platform": "linux", "box_commit": "abc123…", "verdict": "GREEN",
//!   "counts": { "total": 13, "pass": 12, "fail": 0, "error": 0, "skip": 1 },
//!   "by_category": { "policy": { "pass": 7, "fail": 0, "error": 0, "skip": 0 }, … },
//!   "integrity": { "cargo_status": 0, "expected": 13, "recorded": 13, "problems": [] },
//!   "coverage_gate": "full" | "reduced: 2 quarantined cell(s) on this platform",
//!   "quarantine": [ { "id", "platform", "reason", "issue", "owner", "restore_when", "applied" }, … ],
//!   "results": [ { "id", "category", "description", "result", "note" }, … ]
//! }
//! ```
//!
//! The reducer is fail-closed. GREEN needs every case in the compiled manifest
//! recorded exactly once with a known result, no FAIL, no ERROR, at least one PASS,
//! every SKIP either declared by the case's own `platforms:` list or an exact,
//! compiled TEMPORARY QUARANTINE cell carrying exactly its authorized note
//! (`quarantine.rs`, test-integ/QUARANTINE.md), no malformed row, and
//! `cargo test` itself exited 0. Anything else is RED, and `integrity.problems`
//! says why. A nonempty subset of rows, a crashed test binary, or a build that
//! never produced a test cannot read as a pass. While the quarantine list is
//! non-empty for the platform, `coverage_gate` reads `reduced` and the `quarantine`
//! array names every exempted cell: that GREEN is the reduced merge gate, not full
//! qualification.

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

/// One case the suite compiles: its id, the folder it lives in, and the platforms
/// it declares (`platforms:` in `det_case!`); empty means every platform.
/// Generated by `build.rs` from the case files themselves.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CaseSpec {
    pub id: &'static str,
    pub category: &'static str,
    pub platforms: &'static [&'static str],
}

impl CaseSpec {
    /// Whether the case is declared to run on `platform`.
    pub fn applies_to(&self, platform: &str) -> bool {
        self.platforms.is_empty() || self.platforms.contains(&platform)
    }
}

/// Every case in the compiled suite, from the generated manifest.
pub const MANIFEST: &[CaseSpec] = include!(concat!(env!("OUT_DIR"), "/case_manifest.rs"));

/// The result vocabulary a row may carry. Anything else is malformed.
pub const RESULTS: &[&str] = &["PASS", "FAIL", "ERROR", "SKIP"];

/// The note prefix every declared-inapplicable SKIP row carries, written only by
/// `run_case_on`. A SKIP whose note does not start with this is a problem.
pub const SKIP_NOTE_PREFIX: &str = "not applicable on ";

/// The env var `run.sh` sets to `cargo test`'s exit status for `emit-verdict`.
pub const CARGO_STATUS_ENV: &str = "DET_CARGO_STATUS";

/// Where rows and verdict.json live. `$DET_RESULTS_DIR` else `~/det-results`.
pub fn results_dir() -> PathBuf {
    if let Ok(d) = std::env::var("DET_RESULTS_DIR") {
        if !d.is_empty() {
            return PathBuf::from(d);
        }
    }
    crate::user_home().join("det-results")
}

/// One recorded result — serialized as a single-line `<id>.jsonl` file. Field set
/// matches the bash JSONL rows.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct Row {
    pub id: String,
    pub category: String,
    pub description: String,
    pub result: String,
    pub note: String,
}

/// The file a row for `id` is written to (one file per unique id, so parallel
/// tests never contend). The id is sanitized for use as a filename.
pub fn row_file(dir: &Path, id: &str) -> PathBuf {
    dir.join(format!("{}.jsonl", id.replace(['/', '\\'], "_")))
}

/// Write one row for a case. `note` is truncated to 9000 chars.
pub fn write_row(
    dir: &Path,
    id: &str,
    category: &str,
    description: &str,
    result: &str,
    note: &str,
) {
    let row = Row {
        id: id.to_string(),
        category: category.to_string(),
        description: description.to_string(),
        result: result.to_string(),
        note: note.chars().take(9000).collect(),
    };
    if let Ok(line) = serde_json::to_string(&row) {
        let _ = std::fs::write(row_file(dir, id), line + "\n");
    }
}

#[derive(Serialize, Default, Clone, Copy, Debug, PartialEq, Eq)]
pub struct Counts {
    pub total: usize,
    pub pass: usize,
    pub fail: usize,
    pub error: usize,
    pub skip: usize,
}

#[derive(Serialize, Default, Clone, Copy, Debug, PartialEq, Eq)]
pub struct CategoryCounts {
    pub pass: usize,
    pub fail: usize,
    pub error: usize,
    pub skip: usize,
}

/// How the suite executed, independent of what the rows say.
#[derive(Serialize, Clone, Debug, PartialEq, Eq)]
pub struct Integrity {
    /// `cargo test`'s exit status as `run.sh` reported it; `None` when not reported.
    pub cargo_status: Option<i32>,
    /// Cases in the compiled manifest.
    pub expected: usize,
    /// Well-formed rows read.
    pub recorded: usize,
    /// Every reason the verdict is not GREEN that the counts alone would hide.
    pub problems: Vec<String>,
}

#[derive(Serialize, Debug)]
pub struct Summary {
    pub platform: String,
    pub box_commit: String,
    pub verdict: String,
    pub counts: Counts,
    pub by_category: BTreeMap<String, CategoryCounts>,
    pub integrity: Integrity,
    /// `full` when no TEMPORARY QUARANTINE entry applies to this platform; otherwise `reduced: N
    /// quarantined cell(s) on this platform`. A GREEN with `reduced` is the explicitly reduced merge
    /// gate, never full qualification.
    pub coverage_gate: String,
    /// Every TEMPORARY QUARANTINE entry that applies to this platform, with whether its authorized
    /// SKIP row was actually recorded (additive; the collector ignores unknown keys).
    pub quarantine: Vec<crate::quarantine::QuarantineReport>,
    pub results: Vec<Row>,
}

/// What `read_rows` found: the rows that parsed, and a description of every file
/// or line that did not.
#[derive(Default, Debug)]
pub struct Rows {
    pub rows: Vec<Row>,
    pub malformed: Vec<String>,
}

impl Summary {
    /// Reduce `rows` for `platform` against `manifest`. `cargo_status` is the exit
    /// status of `cargo test`, `None` when the caller did not report one.
    pub fn build(
        platform: &str,
        box_commit: &str,
        rows: Rows,
        manifest: &[CaseSpec],
        cargo_status: Option<i32>,
    ) -> Self {
        let Rows {
            mut rows,
            malformed,
        } = rows;
        // Stable order: by id, so verdict.json is deterministic across runs.
        rows.sort_by(|a, b| a.id.cmp(&b.id));

        let mut counts = Counts::default();
        let mut by_category: BTreeMap<String, CategoryCounts> = BTreeMap::new();
        let mut problems: Vec<String> = malformed
            .iter()
            .map(|m| format!("malformed row: {m}"))
            .collect();

        for r in &rows {
            counts.total += 1;
            let cat = by_category.entry(r.category.clone()).or_default();
            match r.result.as_str() {
                "PASS" => {
                    counts.pass += 1;
                    cat.pass += 1;
                }
                "FAIL" => {
                    counts.fail += 1;
                    cat.fail += 1;
                }
                "ERROR" => {
                    counts.error += 1;
                    cat.error += 1;
                }
                "SKIP" => {
                    counts.skip += 1;
                    cat.skip += 1;
                }
                other => problems.push(format!("{}: unknown result {other:?}", r.id)),
            }
        }

        // Every manifest case exactly once; every row a manifest case.
        let mut seen: BTreeMap<&str, usize> = BTreeMap::new();
        for r in &rows {
            *seen.entry(r.id.as_str()).or_default() += 1;
        }
        let known: BTreeSet<&str> = manifest.iter().map(|c| c.id).collect();
        for spec in manifest {
            match seen.get(spec.id).copied().unwrap_or(0) {
                0 => problems.push(format!(
                    "{}: no row recorded (the test never ran, or its binary crashed before recording)",
                    spec.id
                )),
                1 => {}
                n => problems.push(format!("{}: {n} rows recorded (duplicate id)", spec.id)),
            }
        }
        for id in seen.keys() {
            if !known.contains(id) {
                problems.push(format!("{id}: row for a case not in the compiled suite"));
            }
        }

        // A SKIP only where the case declares the platform out, and never where it
        // declares the platform in; category as the folder says.
        for r in &rows {
            let Some(spec) = manifest.iter().find(|c| c.id == r.id) else {
                continue;
            };
            if r.category != spec.category {
                problems.push(format!(
                    "{}: category {:?} but the case lives in {:?}",
                    r.id, r.category, spec.category
                ));
            }
            let applies = spec.applies_to(platform);
            let quarantined = crate::quarantine::lookup(&r.id, platform);
            if r.result == "SKIP" {
                if applies {
                    match quarantined {
                        // The one authorized exception: the compiled cell AND exactly its note.
                        Some(q) if r.note == crate::quarantine::note(q) => {}
                        Some(_) => problems.push(format!(
                            "{}: SKIP on {platform} with a note that is not the authorized TEMPORARY QUARANTINE note \
                             (required coverage not exercised without authorization)",
                            r.id
                        )),
                        None => problems.push(format!(
                            "{}: SKIP on {platform}, but the case is declared for this platform (required coverage not exercised)",
                            r.id
                        )),
                    }
                } else if !r.note.starts_with(SKIP_NOTE_PREFIX) {
                    problems.push(format!(
                        "{}: SKIP without the declared-inapplicable note",
                        r.id
                    ));
                }
            } else if applies && quarantined.is_some() {
                // Runner and reducer read the same list; a recorded PASS/FAIL/ERROR here means they
                // disagreed (a stale build, a bypassed runner). Fail closed.
                problems.push(format!(
                    "{}: recorded {} on {platform}, but the cell is TEMPORARY-QUARANTINED (runner and reducer disagree)",
                    r.id, r.result
                ));
            } else if !applies {
                problems.push(format!(
                    "{}: recorded {} on {platform}, but the case is declared for {:?} only",
                    r.id, r.result, spec.platforms
                ));
            }
        }

        match cargo_status {
            None => problems.push(format!(
                "cargo test exit status not reported ({CARGO_STATUS_ENV} unset): the suite may not have run"
            )),
            Some(0) => {}
            Some(code) if counts.fail == 0 && counts.error == 0 => problems.push(format!(
                "cargo test exited {code} but no recorded row failed: a test outside the harness failed, or a binary crashed"
            )),
            Some(code) => problems.push(format!("cargo test exited {code}")),
        }

        if counts.pass == 0 {
            problems.push("no case passed: nothing was exercised".to_string());
        }

        // GREEN only if every case ran to a known outcome and nothing failed or
        // errored. An ERROR is an infrastructure fault (box never launched, CLI/load
        // refusal) — a case that proved nothing — so it turns the suite RED (the
        // fail-closed behavior added upstream), and so does every integrity problem above.
        let verdict = if counts.fail == 0 && counts.error == 0 && problems.is_empty() {
            "GREEN"
        } else {
            "RED"
        };

        // The exact coverage gap this platform's GREEN would carry, named for reviewers.
        let quarantine: Vec<crate::quarantine::QuarantineReport> =
            crate::quarantine::for_platform(platform)
                .into_iter()
                .map(|q| crate::quarantine::QuarantineReport {
                    id: q.id,
                    platform: q.platform,
                    reason: q.reason,
                    issue: q.issue,
                    owner: q.owner,
                    restore_when: q.restore_when,
                    applied: rows.iter().any(|r| {
                        r.id == q.id && r.result == "SKIP" && r.note == crate::quarantine::note(q)
                    }),
                })
                .collect();
        let coverage_gate = if quarantine.is_empty() {
            "full".to_string()
        } else {
            format!(
                "reduced: {} quarantined cell(s) on this platform",
                quarantine.len()
            )
        };

        Summary {
            platform: platform.to_string(),
            box_commit: box_commit.to_string(),
            verdict: verdict.to_string(),
            counts,
            by_category,
            integrity: Integrity {
                cargo_status,
                expected: manifest.len(),
                recorded: rows.len(),
                problems,
            },
            coverage_gate,
            quarantine,
            results: rows,
        }
    }
}

/// Read every `<id>.jsonl` row from `dir` (ignoring verdict.json). A file that is
/// not exactly one well-formed row, or whose row id does not match its filename, is
/// reported as malformed rather than dropped.
pub fn read_rows(dir: &Path) -> Rows {
    let mut found = Rows::default();
    let Ok(entries) = std::fs::read_dir(dir) else {
        found
            .malformed
            .push(format!("{}: results directory unreadable", dir.display()));
        return found;
    };
    let mut paths: Vec<PathBuf> = entries.flatten().map(|e| e.path()).collect();
    paths.sort();
    for path in paths {
        if path.extension().and_then(|e| e.to_str()) != Some("jsonl") {
            continue;
        }
        let name = path
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or("?")
            .to_string();
        let content = match std::fs::read_to_string(&path) {
            Ok(c) => c,
            Err(e) => {
                found.malformed.push(format!("{name}: unreadable ({e})"));
                continue;
            }
        };
        let lines: Vec<&str> = content
            .lines()
            .map(str::trim)
            .filter(|l| !l.is_empty())
            .collect();
        if lines.len() != 1 {
            found.malformed.push(format!(
                "{name}: {} rows in one file (expected 1)",
                lines.len()
            ));
            continue;
        }
        match serde_json::from_str::<Row>(lines[0]) {
            Ok(row) => {
                if row_file(dir, &row.id) != path {
                    found
                        .malformed
                        .push(format!("{name}: holds a row for id {:?}", row.id));
                } else {
                    // A row with an unknown result is kept too: `Summary::build` reports it by id.
                    found.rows.push(row);
                }
            }
            Err(e) => found.malformed.push(format!("{name}: not a row ({e})")),
        }
    }
    found
}

/// `cargo test`'s exit status as `run.sh` reports it through the environment.
pub fn cargo_status_from_env() -> Option<i32> {
    std::env::var(CARGO_STATUS_ENV).ok()?.trim().parse().ok()
}

/// Reduce the rows in `dir` into `dir/verdict.json`. Returns the built summary.
pub fn emit(dir: &Path) -> std::io::Result<Summary> {
    let summary = Summary::build(
        crate::Platform::current().as_str(),
        &crate::resolve_box_commit(),
        read_rows(dir),
        MANIFEST,
        cargo_status_from_env(),
    );
    let json = serde_json::to_string_pretty(&summary).unwrap_or_default();
    std::fs::write(dir.join("verdict.json"), json + "\n")?;
    Ok(summary)
}

